#!/usr/bin/env python3
"""Derive builds/cascadestudio-jseh.yml (the JS-emulated-exceptions DEBUG
artifact) from builds/cascadestudio.yml: same bindings, same memory/stack
settings, but `cascadestudio-jseh.js` and Emscripten's JS exception model.

  python3 src/deriveJsehYaml.py        # after any edit to cascadestudio.yml

Why keep it: under JS-emulated EH every C++ throw reaches JS as the raw
thrown pointer and execution stays inside ordinary JS frames, which is
easier to step through and to bisect than native wasm EH; it is also the
exception model every CascadeStudio release before 2026-10 shipped, so it is
the A/B reference for "did native EH change this?". It needs its own object
tree (OCJS_EXCEPTIONS=js compileSources.py into a separate OCJS_BUILD_DIR).
"""
import os, sys
here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, '..', 'builds', 'cascadestudio.yml')
dst = os.path.join(here, '..', 'builds', 'cascadestudio-jseh.yml')
text = open(src).read()
def must(old, new):
    global text
    if old not in text:
        sys.exit('deriveJsehYaml: cannot find ' + repr(old) + ' in cascadestudio.yml')
    text = text.replace(old, new, 1)
must('  name: cascadestudio.js\n', '  name: cascadestudio-jseh.js\n')
must('    - "-fwasm-exceptions"\n', '    - "-fexceptions"\n    - "-sDISABLE_EXCEPTION_CATCHING=0"\n')
must('    - "-sEXPORT_EXCEPTION_HANDLING_HELPERS"\n', '')
banner = ('# GENERATED by src/deriveJsehYaml.py from cascadestudio.yml — do not edit.\n'
          '# The JS-emulated-exceptions DEBUG artifact (cascadestudio-jseh.js/.wasm):\n'
          '# identical bindings and memory/stack settings, Emscripten JS EH.\n'
          '# Build its objects with OCJS_EXCEPTIONS=js into their own OCJS_BUILD_DIR.\n')
open(dst, 'w').write(banner + text)
print('wrote ' + os.path.relpath(dst))
